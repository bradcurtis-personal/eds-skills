def test_two_roles_in_sequence_split_effort_by_segment():
    """Acceptance criterion 5: one agent, two roles in sequence, effort split by segment."""
    env = _Env()
    try:
        env.run("assume", "--role", "developer", "--agent", "a1", "--ticket", "EDS-1", now=_ts(10))
        env.run("assume", "--role", "reviewer", "--agent", "a1", "--ticket", "EDS-1", now=_ts(20))
        env.run("release", "--agent", "a1", now=_ts(30))
        transcript = env.root / "session.jsonl"
        _transcript(transcript, [
            (_ts(5), "m0", "sonnet", 10, 5),     # before any segment -> unassigned
            (_ts(12), "m1", "sonnet", 100, 50),  # developer
            (_ts(15), "m2", "sonnet", 200, 100), # developer
            (_ts(20), "m3", "haiku", 40, 10),    # exactly at the switch -> reviewer
            (_ts(25), "m4", "haiku", 60, 40),    # reviewer
            (_ts(35), "m5", "sonnet", 7, 3),     # after the release -> unassigned
        ])
        code, out = env.run("attribute", "--transcript", str(transcript))
        assert code == 0
        assert out["by_role"]["developer"] == 450
        assert out["by_role"]["reviewer"] == 150
        assert out["by_role"]["unassigned"] == 25
        assert out["total_tokens"] == 625, "every token lands in exactly one bucket, none dropped or doubled"
        assert out["unassigned"]["messages"] == 2 and out["flags"], "usage outside a segment is flagged"
        by_role = {s["role"]: s for s in out["segments"]}
        assert by_role["developer"]["messages"] == 2 and by_role["reviewer"]["by_model"] == {"haiku": 150}
    finally:
        env.close()


