def _load_module(workdir):
    previous = os.getcwd()
    os.chdir(workdir)  # the logging bootstrap creates logs/ in the working directory
    try:
        spec = importlib.util.spec_from_file_location("role_assume_main", SKILL_DIR / "main.py")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return module
    finally:
        os.chdir(previous)


class _Env:
    def __init__(self):
        self._tmp = tempfile.TemporaryDirectory()
        root = Path(self._tmp.name)
        self.state = root / "state"
        self.registry = root / "role-registry.yaml"
        self.registry.write_text(REGISTRY_FIXTURE, encoding="utf-8")
        (root / "ROLE_REGISTRY.md").write_text(DOC_FIXTURE, encoding="utf-8")
        self.root = root
        self.module = _load_module(root)

    def run(self, command, *extra, now=None):
        argv = [command, "--registry", str(self.registry), "--state-dir", str(self.state)]
        if now:
            argv += ["--now", now]
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            code = self.module.main(argv + list(extra))
        return code, json.loads(buffer.getvalue())

    def close(self):
        self._tmp.cleanup()


def _ts(minute, second=0):
    return f"2026-11-12T10:{minute:02d}:{second:02d}Z"


def _transcript(path, records):
    lines = []
    for stamp, mid, model, inp, out in records:
        rec = {"timestamp": stamp, "message": {"id": mid, "model": model,
                                               "usage": {"input_tokens": inp, "output_tokens": out}}}
        lines.append(json.dumps(rec))
        lines.append(json.dumps(rec))  # each API message appears twice in the jsonl (decision 30(k))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


